/**
 * Brand assets and team badges (R-231 as amended by PD-28, PD-ARCH-01G-E):
 *
 * - Mi marca registers only the studio's own assets: its categories offer no club badge or competition mark, and a
 *   registered asset is listed.
 * - A club badge is never a brand asset: it is uploaded manually per team in Competiciones, as a PNG or JPEG, with
 *   the source and the operator's declared authorization (PD-28); without the declaration nothing is uploaded.
 * - The engine templates name their badge slots: two on the match result, filled with the badges uploaded in
 *   Competiciones; none on the cover, the standings and the closing slide.
 *
 * Every image is a synthetic PNG generated by the test (e2e/support/png.ts).
 */
import { seedLocalCompetition } from '../support/local-data.js';
import { solidPng } from '../support/png.js';
import { expect, test } from '../support/test.js';

const BADGE_WORDING = /escudo|insignia|emblema|badge|crest|marca de (la )?competici|club/i;

test.describe('Brand assets and team badges (R-231, PD-28)', () => {
  test('Mi marca offers no badge category and lists a registered asset', async ({ page }) => {
    await page.goto('/brand/resources');
    await expect(page.getByRole('heading', { level: 1, name: 'Recursos' })).toBeVisible();
    await page.getByRole('button', { name: 'Subir recurso' }).first().click();
    const dialog = page.getByRole('dialog', { name: 'Subir un recurso de marca' });
    const categories = dialog.getByRole('combobox', { name: 'Categoría' }).getByRole('option');
    await expect(categories).toHaveText(['Logotipo', 'Mascota', 'Elemento gráfico', 'Fondo', 'Referencia gráfica']);
    for (const category of await categories.all()) {
      await expect(category).not.toHaveText(BADGE_WORDING);
    }

    const label = 'Logotipo sintético de prueba';
    await dialog.locator('input[type="file"]').setInputFiles({
      name: 'logotipo-sintetico.png',
      mimeType: 'image/png',
      buffer: solidPng(64, 64, [0x12, 0x5b, 0x3a]),
    });
    await dialog.getByRole('textbox', { name: 'Nombre' }).fill(label);
    await dialog.getByRole('button', { name: 'Guardar recurso' }).click();
    await expect(dialog).toBeHidden();
    await expect(page.getByRole('main')).toContainText(label);
  });

  test('a team badge is uploaded in Competiciones only with its source and the declared authorization', async ({
    page,
    baseURL,
  }) => {
    if (baseURL === undefined) throw new Error('baseURL is not configured');
    const competition = await seedLocalCompetition(page.request, baseURL, { name: 'Liga Sintética Escudos' });
    await page.goto(`/competitions/${competition.competitionId}/teams`);
    await page
      .getByRole('row', { name: /^Club Alfa / })
      .getByRole('button', { name: 'Editar equipo' })
      .click();
    const dialog = page.getByRole('dialog', { name: 'Editar equipo' });
    const badge = dialog.getByRole('region', { name: 'Escudo' });
    await expect(badge).toContainText('Este equipo no tiene escudo.');
    await badge.getByRole('button', { name: 'Subir escudo' }).click();
    await badge.locator('input[type="file"]').setInputFiles({
      name: 'escudo-sintetico.png',
      mimeType: 'image/png',
      buffer: solidPng(256, 256, [0xc8, 0x10, 0x2e]),
    });
    await badge.getByRole('textbox', { name: 'Fuente del escudo' }).fill('Archivo sintético de prueba');
    const authorization = badge.getByRole('checkbox', {
      name: 'Confirmo que tengo autorización para usar este escudo.',
    });
    const upload = badge.getByRole('button', { name: 'Subir escudo' });
    // Without the declared authorization the form refuses the upload and nothing is stored.
    await expect(authorization).not.toBeChecked();
    await upload.click();
    await expect(badge.getByText('Confirma la autorización para subir el escudo.')).toBeVisible();
    const before = await page.request.get(`/api/v1/teams/${competition.teams[0]?.id ?? ''}/badge`);
    expect(before.status()).toBe(404);
    await authorization.check();
    await upload.click();
    await expect(badge).not.toContainText('Este equipo no tiene escudo.');
    const after = await page.request.get(`/api/v1/teams/${competition.teams[0]?.id ?? ''}/badge`);
    expect(after.status()).toBe(200);
  });

  test('the engine templates name their badge slots', async ({ page }) => {
    await page.goto('/templates/engine');
    await expect(page.getByRole('heading', { level: 1, name: 'Plantillas del motor' })).toBeVisible();
    const slotsOf = (name: string) =>
      page
        .getByRole('listitem')
        .filter({ has: page.getByRole('heading', { level: 3, name, exact: true }) })
        .locator('dt', { hasText: 'Espacios para escudos' })
        .locator('xpath=following-sibling::dd[1]');
    await expect(slotsOf('Resultado de partido')).toHaveText(
      '2 espacios con los escudos subidos en Competiciones; un equipo sin escudo deja su espacio vacío.',
    );
    for (const name of ['Portada', 'Tabla de posiciones', 'Cierre']) {
      await expect(slotsOf(name)).toHaveText('Ninguno');
    }
  });
});
