/**
 * Synthetic local sports data for the journeys (UI-06.1). Since PD-ARCH-01F the studio creates content only from
 * competitions managed locally (Competiciones), so a journey needs a competition, a season, teams, rounds and matches
 * before it opens Crear contenido. They are created here through the API, the way the Competiciones pages call it
 * (same origin, `X-EDR-Client: web`), because managing a competition is not the journey under test; the creation, the
 * review, the approvals and the download are always performed through the interface (e2e/support/app.ts).
 *
 * Every name is synthetic. Optional team badges are solid-colour PNG files generated by the test and uploaded with
 * the declared authorization the operator gives in the interface (PD-28: PNG or JPEG, manual upload only).
 */
import type { APIRequestContext } from '@playwright/test';

import { solidPng } from './png.js';
import { expect } from './test.js';

export interface LocalTeam {
  readonly id: string;
  readonly name: string;
}

export interface LocalRound {
  readonly id: string;
  readonly name: string;
  /** Option label of the round in Crear contenido (`<name> (<n> partidos)`). */
  readonly option: string;
}

export interface LocalCompetition {
  readonly competitionId: string;
  readonly name: string;
  readonly seasonId: string;
  readonly seasonLabel: string;
  readonly teams: readonly LocalTeam[];
  /** Two finished matches with scores: Alfa 2-1 Beta, Gamma 0-0 Delta. */
  readonly played: LocalRound;
  /** Two scheduled matches with a future kickoff. */
  readonly upcoming: LocalRound;
}

export interface SeedOptions {
  /**
   * Base of the competition name, one per journey. A short token unique to the call is appended to it and to the team
   * names (`Club Alfa <token>`), because local teams are shared by every competition and their names are unique, and
   * because Playwright prepares a suite's data again in a new worker after a failure.
   */
  readonly name: string;
  /** Upload a synthetic badge for every team (PD-28). */
  readonly badges?: boolean;
}

const TEAM_NAMES = ['Club Alfa', 'Club Beta', 'Club Gamma', 'Club Delta'] as const;

let seeded = 0;

/** A short token unique to each seed of a run (letters and digits, allowed in names by the `TeamName` rule). */
function uniqueToken(): string {
  seeded += 1;
  return (Date.now() * 100 + seeded).toString(36).slice(-6);
}
const BADGE_COLOURS: readonly (readonly [number, number, number])[] = [
  [0xc8, 0x10, 0x2e],
  [0x00, 0x4b, 0x9b],
  [0x00, 0x7a, 0x3d],
  [0xf2, 0xa9, 0x00],
];

function clientHeaders(baseURL: string): Record<string, string> {
  return { 'X-EDR-Client': 'web', Origin: new URL(baseURL).origin };
}

async function created(
  request: APIRequestContext,
  baseURL: string,
  path: string,
  data: unknown,
): Promise<{ id: string }> {
  const response = await request.post(`/api/v1${path}`, { headers: clientHeaders(baseURL), data });
  expect([200, 201], `POST ${path}: ${await response.text()}`).toContain(response.status());
  return (await response.json()) as { id: string };
}

/** Uploads a synthetic PNG badge for a team with the declared authorization (PD-28). */
export async function uploadTeamBadge(
  request: APIRequestContext,
  baseURL: string,
  teamId: string,
  rgb: readonly [number, number, number],
): Promise<void> {
  const response = await request.put(`/api/v1/teams/${teamId}/badge`, {
    headers: { ...clientHeaders(baseURL), 'Content-Type': 'image/png' },
    params: { source: 'Archivo sintético de prueba', authorized: 'true' },
    data: solidPng(256, 256, rgb),
  });
  expect(response.status(), `PUT badge: ${await response.text()}`).toBe(200);
}

/**
 * Creates a local competition with season 2026/27, four teams, a played round (two finished matches) and an upcoming
 * round (two scheduled matches).
 */
export async function seedLocalCompetition(
  request: APIRequestContext,
  baseURL: string,
  options: SeedOptions,
): Promise<LocalCompetition> {
  const token = uniqueToken();
  const name = `${options.name} ${token}`;
  const competitionId = (await created(request, baseURL, '/competitions', { name })).id;
  const seasonLabel = '2026/27';
  const seasonId = (await created(request, baseURL, `/competitions/${competitionId}/seasons`, { label: seasonLabel }))
    .id;
  const base = `/competitions/${competitionId}/seasons/${seasonId}`;
  const teams: LocalTeam[] = [];
  for (const [index, teamName] of TEAM_NAMES.entries()) {
    const team = await created(request, baseURL, '/teams', { name: `${teamName} ${token}` });
    await created(request, baseURL, `/competitions/${competitionId}/teams`, { teamId: team.id });
    if (options.badges === true) {
      await uploadTeamBadge(request, baseURL, team.id, BADGE_COLOURS[index] ?? [0x80, 0x80, 0x80]);
    }
    teams.push({ id: team.id, name: `${teamName} ${token}` });
  }
  await created(request, baseURL, `${base}/participants/batch`, { teamIds: teams.map((team) => team.id) });
  const round = async (name: string): Promise<LocalRound> => ({
    id: (await created(request, baseURL, `${base}/rounds`, { name })).id,
    name,
    option: `${name} (2 partidos)`,
  });
  const played = await round('Jornada 1');
  const upcoming = await round('Jornada 2');
  const match = async (
    home: number,
    away: number,
    roundId: string,
    kickoffAt: string,
    result: { homeScore: number; awayScore: number } | null,
  ): Promise<void> => {
    const { id } = await created(request, baseURL, `${base}/matches`, {
      homeTeamId: teams[home]?.id,
      awayTeamId: teams[away]?.id,
      kickoffAt,
      stageId: null,
      roundId,
    });
    if (result !== null) {
      await created(request, baseURL, `${base}/matches/${id}/result`, { status: 'finished', ...result });
    }
  };
  await match(0, 1, played.id, '2026-10-20T18:00:00.000Z', { homeScore: 2, awayScore: 1 });
  await match(2, 3, played.id, '2026-10-20T20:00:00.000Z', { homeScore: 0, awayScore: 0 });
  await match(0, 2, upcoming.id, '2027-01-20T18:00:00.000Z', null);
  await match(1, 3, upcoming.id, '2027-01-20T20:00:00.000Z', null);
  return { competitionId, name, seasonId, seasonLabel, teams, played, upcoming };
}
