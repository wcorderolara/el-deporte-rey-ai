import type { TeamBadge } from '@edr/contracts';

/** Domain values owned by the local competition administration module. */
export interface LocalSeason {
  readonly id: string;
  readonly competitionId: string;
  readonly label: string;
  readonly createdAt: string;
}

export interface LocalTeam {
  readonly id: string;
  /** The official name: identity, matching, imports and editorial copy (BR-05, PD-06). */
  readonly name: string;
  /**
   * Optional presentation name the operator sets for the carousel images only (TEAM-DISPLAY-01, PD-37), or null.
   * Never written by an import, never generated by AI and never derived from a provider short name or code.
   */
  readonly displayName: string | null;
  readonly region: string | null;
  /** The active badge (PD-ARCH-01G-D), or null. */
  readonly badge: TeamBadge | null;
  readonly createdAt: string;
  readonly updatedAt: string;
}

export interface SeasonParticipant {
  readonly team: LocalTeam;
  readonly joinedAt: string;
}

export interface CompetitionTeam {
  readonly team: LocalTeam;
  readonly associatedAt: string;
}
